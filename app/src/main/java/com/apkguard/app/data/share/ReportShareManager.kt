package com.apkguard.app.data.share

import android.content.Context
import android.content.Intent
import android.graphics.Bitmap
import android.graphics.Canvas
import android.graphics.Color
import android.text.Layout
import android.text.StaticLayout
import android.text.TextPaint
import androidx.core.content.FileProvider
import com.apkguard.app.domain.model.LocalizedText
import com.apkguard.app.domain.model.ScanReport
import com.apkguard.app.domain.model.Severity
import com.apkguard.app.domain.model.Verdict
import java.io.File
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/**
 * Builds the shareable report: a plain-text summary and a rendered PNG card.
 * The card is drawn with android.graphics (not a Compose hierarchy) so it can be
 * generated from anywhere, including outside composition.
 */
class ReportShareManager(private val context: Context) {

    fun shareText(report: ScanReport, isThai: Boolean) {
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_TEXT, buildText(report, isThai))
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        }
        context.startActivity(Intent.createChooser(intent, null).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK))
    }

    fun shareImage(report: ScanReport, isThai: Boolean) {
        val file = runCatching { renderCard(report, isThai) }.getOrNull() ?: return
        val uri = FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", file)
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "image/png"
            putExtra(Intent.EXTRA_STREAM, uri)
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        context.startActivity(Intent.createChooser(intent, null).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK))
    }

    fun buildText(report: ScanReport, isThai: Boolean): String = buildString {
        val l = { t: LocalizedText -> t.resolve(isThai) }
        appendLine(if (isThai) "🔐 APK Guard — รายงานการตรวจสอบ" else "🔐 APK Guard — Security report")
        appendLine("${label(isThai, "แอป", "App")}: ${report.identity.appName ?: "?"}")
        report.identity.packageName?.let { appendLine("${label(isThai, "แพ็กเกจ", "Package")}: $it") }
        report.identity.versionName?.let { appendLine("${label(isThai, "เวอร์ชัน", "Version")}: $it") }
        appendLine("${label(isThai, "ผลการตรวจ", "Verdict")}: ${l(verdictText(report.verdict))} (${report.verdict})")
        appendLine("${label(isThai, "คะแนนความเสี่ยง", "Risk score")}: ${report.score}/100")
        report.vt?.let { vt ->
            appendLine("VirusTotal: ${vt.malicious}/${vt.totalEngines}")
        }
        val notable = report.findings.filter { it.severity != Severity.INFO }
        if (notable.isEmpty()) {
            appendLine(label(isThai, "ไม่พบสิ่งผิดปกติจากการตรวจบนเครื่อง", "Nothing suspicious found on-device"))
        } else {
            appendLine("${label(isThai, "สิ่งที่พบ", "Findings")}:")
            notable.take(8).forEach { appendLine("• ${l(it.title)}") }
        }
        report.sha256?.let { appendLine("SHA-256: $it") }
        appendLine()
        appendLine(label(isThai, "สร้างโดยแอป APK Guard", "Generated by APK Guard"))
    }

    // ---------------------------------------------------------------- card

    private val cardWidth = 1080
    private val cardHeight = 1440
    private val padding = 72f

    private fun verdictColor(verdict: Verdict): Int = when (verdict) {
        Verdict.SAFE -> Color.rgb(0x17, 0x72, 0x45)
        Verdict.SUSPICIOUS -> Color.rgb(0xB3, 0x6A, 0x00)
        Verdict.DANGEROUS -> Color.rgb(0xA3, 0x16, 0x21)
    }

    private fun renderCard(report: ScanReport, isThai: Boolean): File {
        val locale = if (isThai) Locale("th") else Locale.ENGLISH
        val bitmap = Bitmap.createBitmap(cardWidth, cardHeight, Bitmap.Config.ARGB_8888)
        val canvas = Canvas(bitmap)
        canvas.drawColor(verdictColor(report.verdict))

        val white = { alpha: Int -> Color.argb(alpha, 0xFF, 0xFF, 0xFF) }
        var y = padding

        // Brand
        y += drawText(canvas, "APK Guard", padding, y, textPaint(white(200), 44f))

        // App name + package
        y += 36f
        y += drawBlock(canvas, report.identity.appName ?: "?", padding, y, textPaint(white(255), 76f, bold = true))
        report.identity.packageName?.let {
            y += drawBlock(canvas, it, padding, y, textPaint(white(210), 40f))
        }

        // Verdict + score
        y += 56f
        y += drawBlock(
            canvas,
            verdictText(report.verdict).resolve(isThai),
            padding,
            y,
            textPaint(white(255), 140f, bold = true),
        )
        y += drawText(canvas, " ${report.score}/100", padding, y, textPaint(white(230), 64f))
        y += drawText(
            canvas,
            label(isThai, "คะแนนความเสี่ยง", "Risk score"),
            padding,
            y + 8f,
            textPaint(white(200), 40f),
        )

        // Findings
        y += 72f
        val notable = report.findings.filter { it.severity != Severity.INFO }
        if (notable.isEmpty()) {
            y += drawBlock(
                canvas,
                label(isThai, "ไม่พบสิ่งผิดปกติจากการตรวจบนเครื่อง", "Nothing suspicious found on-device"),
                padding,
                y,
                textPaint(white(240), 44f),
            )
        } else {
            notable.take(4).forEach { f ->
                y += drawBlock(canvas, "•  ${f.title.resolve(isThai)}", padding, y, textPaint(white(245), 44f))
                y += 12f
            }
            val rest = notable.size - 4
            if (rest > 0) {
                y += drawBlock(
                    canvas,
                    label(isThai, "และอีก $rest รายการ", "+ $rest more"),
                    padding,
                    y,
                    textPaint(white(220), 40f),
                )
            }
        }
        report.vt?.let { vt ->
            y += 24f
            y += drawBlock(
                canvas,
                "VirusTotal: ${vt.malicious}/${vt.totalEngines}",
                padding,
                y,
                textPaint(white(240), 44f),
            )
        }

        // Footer
        val date = SimpleDateFormat.getDateTimeInstance(SimpleDateFormat.SHORT, SimpleDateFormat.SHORT, locale)
            .format(Date(report.scannedAtMs))
        val footerPaint = textPaint(white(190), 36f)
        canvas.drawText(date, padding, cardHeight - padding, footerPaint)
        canvas.drawText(
            "APK Guard",
            cardWidth - padding - footerPaint.measureText("APK Guard"),
            cardHeight - padding,
            footerPaint,
        )

        val dir = File(context.cacheDir, "shared").apply { mkdirs() }
        val file = File(dir, "apk_guard_report.png")
        file.outputStream().use { bitmap.compress(Bitmap.CompressFormat.PNG, 100, it) }
        bitmap.recycle()
        return file
    }

    private fun textPaint(color: Int, size: Float, bold: Boolean = false) = TextPaint().apply {
        this.color = color
        this.textSize = size
        isAntiAlias = true
        isFakeBoldText = bold
    }

    private fun drawText(canvas: Canvas, text: String, x: Float, y: Float, paint: TextPaint): Float {
        val baseline = y + paint.textSize
        canvas.drawText(text, x, baseline, paint)
        return paint.textSize + 14f
    }

    /** Draws wrapped text and returns the consumed height. */
    private fun drawBlock(canvas: Canvas, text: String, x: Float, y: Float, paint: TextPaint): Float {
        val width = (cardWidth - 2 * padding).toInt()
        val layout = StaticLayout.Builder.obtain(text, 0, text.length, paint, width)
            .setAlignment(Layout.Alignment.ALIGN_NORMAL)
            .setLineSpacing(0f, 1.15f)
            .setIncludePad(false)
            .build()
        canvas.save()
        canvas.translate(x, y)
        layout.draw(canvas)
        canvas.restore()
        return layout.height + 22f
    }

    private fun verdictText(verdict: Verdict): LocalizedText = when (verdict) {
        Verdict.SAFE -> LocalizedText("ปลอดภัย", "SAFE")
        Verdict.SUSPICIOUS -> LocalizedText("น่าสงสัย", "SUSPICIOUS")
        Verdict.DANGEROUS -> LocalizedText("อันตราย", "DANGEROUS")
    }

    private fun label(isThai: Boolean, th: String, en: String) = if (isThai) th else en
}
